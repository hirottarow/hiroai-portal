def collect_pageable_items(templates, site_only):
    """(item, is_site_only) のリストを ticker 重複なしで返す。"""
    items = []
    seen = set()
    for t in templates:
        ticker = t.get("ticker")
        if not ticker:
            raise ValueError(f"ticker が空です: {t.get('company')}")
        if ticker in seen:
            raise ValueError(f"ticker が重複しています: {ticker}")
        seen.add(ticker)
        items.append((t, False))
    for t in site_only:
        ticker = t.get("ticker")
        if not ticker:
            raise ValueError(f"ticker が空です(siteOnly): {t.get('company')}")
        if ticker in seen:
            raise ValueError(f"ticker が templates と siteOnly で重複しています: {ticker}")
        seen.add(ticker)
        items.append((t, True))
    return items


def write_pages(items, quo_items, updated_at):
    os.makedirs(BENEFITS_DIR, exist_ok=True)
    existing = set(os.path.basename(p) for p in glob.glob(os.path.join(BENEFITS_DIR, "*.html")))
    written = set()

    for t, is_site_only in items:
        fname = f"{t['ticker']}.html"
        path = os.path.join(BENEFITS_DIR, fname)
        content = build_page(t, updated_at, is_site_only=is_site_only)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        written.add(fname)

    quo_path = os.path.join(BENEFITS_DIR, QUO_FILENAME)
    with open(quo_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(build_quo_page(quo_items, updated_at))
    written.add(QUO_FILENAME)

    stale = existing - written
    for fname in stale:
        os.remove(os.path.join(BENEFITS_DIR, fname))
    return written, stale


def update_benefits_html(items):
    with open(BENEFITS_HTML, encoding="utf-8") as f:
        content = f.read()

    templates_sorted = sorted((t for t, so in items if not so), key=lambda t: t.get("ticker", ""))
    site_only_sorted = sorted((t for t, so in items if so), key=lambda t: t.get("ticker", ""))

    lines = [STATIC_LIST_BEGIN, '<ul class="static-benefit-list">']
    for t in templates_sorted:
        lines.append(f'<li><a href="benefits/{esc(t["ticker"])}.html">{esc(t["company"])}</a></li>')
    lines.append("</ul>")

    if site_only_sorted:
        lines.append('<h3 class="static-benefit-subhead">QUOカードなど（優待辞書には未収録）</h3>')
        lines.append('<ul class="static-benefit-list">')
        for t in site_only_sorted:
            lines.append(f'<li><a href="benefits/{esc(t["ticker"])}.html">{esc(t["company"])}</a></li>')
        lines.append(f'<li><a href="benefits/{QUO_FILENAME}">QUOカード優待 銘柄一覧（比較表）</a></li>')
        lines.append("</ul>")

    lines.append(STATIC_LIST_END)
    block = "\n".join(lines)

    old_list_div = '<div id="list"><div class="status">読み込み中…</div></div>'
    new_list_div = f'<div id="list">\n{block}\n</div>'

    if STATIC_LIST_BEGIN in content:
        pattern = re.compile(
            re.escape(STATIC_LIST_BEGIN) + r".*?" + re.escape(STATIC_LIST_END), re.S
        )
        content, n = pattern.subn(block, content, count=1)
        if n != 1:
            raise ValueError("既存の静的一覧ブロックの置換に失敗しました")
    elif old_list_div in content:
        content = content.replace(old_list_div, new_list_div, 1)
    else:
        raise ValueError("benefits.html に挿入先(#list)が見つかりません")

