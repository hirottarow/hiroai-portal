def star_text(rating):
    try:
        n = max(0, min(5, int(rating)))
    except (TypeError, ValueError):
        return None
    return "★" * n + "☆" * (5 - n)


def build_info_items(t):
    items = []
    if t.get("category"):
        items.append(("カテゴリ", t["category"]))
    if t.get("exchange"):
        items.append(("上場市場", t["exchange"]))
    if t.get("balance"):
        unit = t.get("balanceUnit") or "円"
        items.append(("優待の目安", f"{t['balance']:,}{unit}"))
    stars = star_text(t.get("rating"))
    if stars:
        items.append(("おすすめ度", stars))
    html_lines = []
    for label, value in items:
        html_lines.append(
            f'            <div class="info-item"><div class="label">{esc(label)}</div>'
            f'<div class="value">{esc(value)}</div></div>'
        )
    return "\n".join(html_lines)


def build_sections(t):
    sections = []
    if t.get("usableStores"):
        sections.append(("使えるお店", t["usableStores"]))
    if t.get("usageNotes"):
        sections.append(("使い方の注意", t["usageNotes"]))
    if t.get("description"):
        sections.append(("詳しい情報", t["description"]))
    if t.get("shipMonths"):
        months = ",".join(m.strip() + "月" for m in str(t["shipMonths"]).split(",") if m.strip())
        if months:
            sections.append(("発送目安", months + "ごろ"))
    html_blocks = []
    for label, value in sections:
        html_blocks.append(
            f'        <div class="section"><h2>{esc(label)}</h2><p>{esc(value)}</p></div>'
        )
    return "\n".join(html_blocks)


def build_description(t):
    parts = [f"{t['company']}（{t['ticker']}）の株主優待「{t.get('title') or t['company']}」の詳細ページです。"]
    if t.get("category"):
        parts.append(f"カテゴリ: {t['category']}。")
    if t.get("balance"):
        unit = t.get("balanceUnit") or "円"
        parts.append(f"優待の目安は{t['balance']:,}{unit}です。")
    return "".join(parts)


def build_page(t, updated_at):
    ticker = t["ticker"]
    company = t["company"]
    title = f"{company}（{ticker}）の株主優待 | ひろ@AI遊び場"
    description = build_description(t)
    canonical = f"{BASE_URL}benefits/{ticker}.html"

    jsonld = {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "ホーム", "item": f"{BASE_URL}index.html"},
            {"@type": "ListItem", "position": 2, "name": "株主優待", "item": f"{BASE_URL}benefits.html"},
            {"@type": "ListItem", "position": 3, "name": company, "item": canonical},
        ],
    }

    audited_line = ""
    if t.get("auditedAt"):
        audited_line = f" ／ 銘柄情報の最終確認日: {esc(t['auditedAt'])}"

    return PAGE_TEMPLATE.format(
        title=esc(title),
        description=esc(description),
        canonical=canonical,
        base=BASE_URL,
        jsonld=json.dumps(jsonld, ensure_ascii=False, indent=2),
        company_esc=esc(company),
        ticker_esc=esc(ticker),
        title_esc=esc(t.get("title") or ""),
        info_items=build_info_items(t),
        sections=build_sections(t),
        updated_at_esc=esc(updated_at),
        audited_line=audited_line,
    )


def write_pages(templates, updated_at):
    os.makedirs(BENEFITS_DIR, exist_ok=True)
    existing = set(os.path.basename(p) for p in glob.glob(os.path.join(BENEFITS_DIR, "*.html")))
    written = set()
    for t in templates:
        ticker = t.get("ticker")
        if not ticker:
            raise ValueError(f"ticker が空です: {t.get('company')}")
        fname = f"{ticker}.html"
        path = os.path.join(BENEFITS_DIR, fname)
        content = build_page(t, updated_at)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        written.add(fname)
    stale = existing - written
    for fname in stale:
        os.remove(os.path.join(BENEFITS_DIR, fname))
    return written, stale


def update_benefits_html(templates):
    with open(BENEFITS_HTML, encoding="utf-8") as f:
        content = f.read()

    items = sorted(templates, key=lambda t: t.get("ticker", ""))
    lines = [STATIC_LIST_BEGIN, '<ul class="static-benefit-list">']
    for t in items:
        ticker = t["ticker"]
        company = t["company"]
        lines.append(f'<li><a href="benefits/{esc(ticker)}.html">{esc(company)}</a></li>')
    lines.append("</ul>")
    lines.append(STATIC_LIST_END)
    block = "\n".join(lines)

    old_list_div = '<div id="list"><div class="status">読み込み中…</div></div>'
    new_list_div = f'<div id="list">\n{block}\n</div>'

    if STATIC_LIST_BEGIN in content:
        pattern = re.compile(
            re.escape(STATIC_LIST_BEGIN) + r".*?" + re.escape(STATIC_LIST_END), re.S
        )
        content, n = pattern.subn(block, content, count=1)
        if n != 1:
            raise ValueError("既存の静的一覧ブロックの置換に失敗しました")
    elif old_list_div in content:
        content = content.replace(old_list_div, new_list_div, 1)
    else:
        raise ValueError("benefits.html に挿入先(#list)が見つかりません")

    with open(BENEFITS_HTML, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


def build_sitemap(templates, updated_at):
    top_files = sorted(
        f for f in glob.glob(os.path.join(ROOT, "*.html"))
        if not is_excluded(os.path.basename(f))
    )

    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']

    for path in top_files:
        fname = os.path.basename(path)
        lm = git_lastmod(fname)
        lines.append("  <url>")
        lines.append(f"    <loc>{BASE_URL}{fname}</loc>")
        if lm:
            lines.append(f"    <lastmod>{lm}</lastmod>")
        lines.append("  </url>")

    for t in sorted(templates, key=lambda x: x.get("ticker", "")):
        ticker = t["ticker"]
        lines.append("  <url>")
        lines.append(f"    <loc>{BASE_URL}benefits/{ticker}.html</loc>")
        lines.append(f"    <lastmod>{updated_at}</lastmod>")
        lines.append("  </url>")

    lines.append("</urlset>")
    lines.append("")

    with open(SITEMAP_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    return len(top_files) + len(templates)


def main():
    data = load_data()
    templates = data.get("templates", [])
    updated_at = data.get("updatedAt", "")

    written, stale = write_pages(templates, updated_at)
    update_benefits_html(templates)
    url_count = build_sitemap(templates, updated_at)

    print(f"templates: {len(templates)}")
    print(f"pages written: {len(written)}")
    print(f"stale pages removed: {len(stale)}")
    print(f"sitemap urls: {url_count}")


if __name__ == "__main__":
    main()
