def build_sitemap(items, updated_at):
    top_files = sorted(
        f for f in glob.glob(os.path.join(ROOT, "*.html"))
        if not is_excluded(os.path.basename(f))
    )

    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']

    for path in top_files:
        fname = os.path.basename(path)
        lm = git_lastmod(fname)
        lines.append("  <url>")
        lines.append(f"    <loc>{BASE_URL}{fname}</loc>")
        if lm:
            lines.append(f"    <lastmod>{lm}</lastmod>")
        lines.append("  </url>")

    benefit_files = sorted([t["ticker"] + ".html" for t, _ in items]) + [QUO_FILENAME]
    for fname in benefit_files:
        lines.append("  <url>")
        lines.append(f"    <loc>{BASE_URL}benefits/{fname}</loc>")
        lines.append(f"    <lastmod>{updated_at}</lastmod>")
        lines.append("  </url>")

    lines.append("</urlset>")
    lines.append("")

    with open(SITEMAP_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    return len(top_files) + len(benefit_files)


