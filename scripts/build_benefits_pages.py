def star_text(rating):
    try:
        n = max(0, min(5, int(rating)))
    except (TypeError, ValueError):
        return None
    return "★" * n + "☆" * (5 - n)


def build_info_items(t):
    items = []
    if t.get("category"):
        items.append(("カテゴリ", t["category"]))
    if t.get("exchange"):
        items.append(("上場市場", t["exchange"]))
    if t.get("balance"):
        unit = t.get("balanceUnit") or "円"
        items.append(("優待の目安", f"{t['balance']:,}{unit}"))
    stars = star_text(t.get("rating"))
    if stars:
        items.append(("おすすめ度", stars))
    html_lines = []
    for label, value in items:
        html_lines.append(
            f'            <div class="info-item"><div class="label">{esc(label)}</div>'
            f'<div class="value">{esc(value)}</div></div>'
        )
    return "\n".join(html_lines)


def build_sections(t):
    sections = []
    if t.get("usableStores"):
        sections.append(("使えるお店", t["usableStores"]))
    if t.get("usageNotes"):
        sections.append(("使い方の注意", t["usageNotes"]))
    if t.get("description"):
        sections.append(("詳しい情報", t["description"]))
    if t.get("shipMonths"):
        months = ship_months_text(t["shipMonths"])
        if months:
            sections.append(("発送目安", months))
    html_blocks = []
    for label, value in sections:
        html_blocks.append(
            f'        <div class="section"><h2>{esc(label)}</h2><p>{esc(value)}</p></div>'
        )
    return "\n".join(html_blocks)


def ship_months_text(raw):
    months = ",".join(m.strip() + "月" for m in str(raw).split(",") if m.strip())
    return months + "ごろ" if months else ""


def build_description(t):
    parts = [f"{t['company']}（{t['ticker']}）の株主優待「{t.get('title') or t['company']}」の詳細ページです。"]
    if t.get("category"):
        parts.append(f"カテゴリ: {t['category']}。")
    if t.get("balance"):
        unit = t.get("balanceUnit") or "円"
        parts.append(f"優待の目安は{t['balance']:,}{unit}です。")
    return "".join(parts)


