# トップレベルの sitemap から除外するページ
# - tool-japan-map-display.html: OBS表示専用ビュー、単独ページとして無意味
# - google*.html: Search Console 所有権確認用トークンファイル、検索対象コンテンツではない
EXCLUDE_FROM_TOP_SITEMAP = {"tool-japan-map-display.html"}
EXCLUDE_PATTERNS = (re.compile(r"^google[0-9a-f]+\.html$"),)


def is_excluded(fname):
    if fname in EXCLUDE_FROM_TOP_SITEMAP:
        return True
    return any(p.match(fname) for p in EXCLUDE_PATTERNS)


def esc(value):
    return html.escape(str(value), quote=True)


def load_data():
    with open(DATA_PATH, encoding="utf-8") as f:
        return json.load(f)


def git_lastmod(relpath):
    out = subprocess.run(
        ["git", "log", "-1", "--format=%ad", "--date=short", "--", relpath],
        capture_output=True, text=True, cwd=ROOT,
    ).stdout.strip()
    return out or None


